import * as esbuild from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

await esbuild.build({
  entryPoints: [resolve(root, "src/app.js")],
  bundle: true,
  format: "iife",
  target: "es2020",
  // Unminified so PR diffs of generated bundle stay readable.
  minify: false,
  outfile: resolve(root, "app.bundle.js"),
  banner: { js: "// Generated by build/bundle.mjs from src/. Do not edit." },
  logLevel: "info",
});
